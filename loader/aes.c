static const uint8_t rcon[11] = {0x00, 0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40, 0x80, 0x1b, 0x36};

typedef struct {
    uint8_t round_key[240]; /* 60 words */
    uint8_t n_rounds;
} aes256_ctx;

static uint8_t xtime(uint8_t x) { return (uint8_t)((x << 1) ^ (((x >> 7) & 1) * 0x1b)); }

static uint8_t gmul(uint8_t a, uint8_t b) {
    uint8_t p = 0;
    for (int i = 0; i < 8; i++) {
        if (b & 1) p ^= a;
        uint8_t hi = a & 0x80;
        a = (uint8_t)(a << 1);
        if (hi) a ^= 0x1b;
        b >>= 1;
    }
    return p;
}

static void key_expansion(aes256_ctx *ctx, const uint8_t key[32]) {
    uint8_t *rk = ctx->round_key;
    for (int i = 0; i < 8; i++) {
        rk[i*4+0] = key[i*4+0];
        rk[i*4+1] = key[i*4+1];
        rk[i*4+2] = key[i*4+2];
        rk[i*4+3] = key[i*4+3];
    }
    uint8_t temp[4];
    for (int i = 8; i < 60; i++) {
        temp[0] = rk[(i-1)*4+0];
        temp[1] = rk[(i-1)*4+1];
        temp[2] = rk[(i-1)*4+2];
        temp[3] = rk[(i-1)*4+3];
        if (i % 8 == 0) {
            uint8_t t = temp[0];
            temp[0] = (uint8_t)(sbox[temp[1]] ^ rcon[i/8]);
            temp[1] = sbox[temp[2]];
            temp[2] = sbox[temp[3]];
            temp[3] = sbox[t];
        } else if (i % 8 == 4) {
            temp[0] = sbox[temp[0]];
            temp[1] = sbox[temp[1]];
            temp[2] = sbox[temp[2]];
            temp[3] = sbox[temp[3]];
        }
        rk[i*4+0] = rk[(i-8)*4+0] ^ temp[0];
        rk[i*4+1] = rk[(i-8)*4+1] ^ temp[1];
        rk[i*4+2] = rk[(i-8)*4+2] ^ temp[2];
        rk[i*4+3] = rk[(i-8)*4+3] ^ temp[3];
    }
    ctx->n_rounds = 14;
}

static void add_round_key(uint8_t s[16], const uint8_t *rk) {
    for (int i = 0; i < 16; i++) s[i] ^= rk[i];
}

static void sub_bytes(uint8_t s[16]) {
    for (int i = 0; i < 16; i++) s[i] = sbox[s[i]];
}

static void inv_sub_bytes(uint8_t s[16]) {
    for (int i = 0; i < 16; i++) s[i] = rsbox[s[i]];
}

static void shift_rows(uint8_t s[16]) {
    uint8_t t;
    t = s[1]; s[1] = s[5]; s[5] = s[9]; s[9] = s[13]; s[13] = t;
    t = s[2]; s[2] = s[10]; s[10] = t;
    t = s[6]; s[6] = s[14]; s[14] = t;
    t = s[3]; s[3] = s[15]; s[15] = s[11]; s[11] = s[7]; s[7] = t;
}

static void inv_shift_rows(uint8_t s[16]) {
    uint8_t t;
    t = s[13]; s[13] = s[9]; s[9] = s[5]; s[5] = s[1]; s[1] = t;
    t = s[2]; s[2] = s[10]; s[10] = t;
    t = s[6]; s[6] = s[14]; s[14] = t;
    t = s[7]; s[7] = s[11]; s[11] = s[15]; s[15] = s[3]; s[3] = t;
}

static void mix_columns(uint8_t s[16]) {
    for (int c = 0; c < 16; c += 4) {
        uint8_t a0 = s[c+0], a1 = s[c+1], a2 = s[c+2], a3 = s[c+3];
        uint8_t t0 = (uint8_t)(a0 ^ a1 ^ a2 ^ a3);
        s[c+0] ^= (uint8_t)(xtime((uint8_t)(a0 ^ a1)) ^ t0);
        s[c+1] ^= (uint8_t)(xtime((uint8_t)(a1 ^ a2)) ^ t0);
        s[c+2] ^= (uint8_t)(xtime((uint8_t)(a2 ^ a3)) ^ t0);
        s[c+3] ^= (uint8_t)(xtime((uint8_t)(a3 ^ a0)) ^ t0);
    }
}

static void inv_mix_columns(uint8_t s[16]) {
    for (int c = 0; c < 16; c += 4) {
        uint8_t a0 = s[c+0], a1 = s[c+1], a2 = s[c+2], a3 = s[c+3];
        s[c+0] = (uint8_t)(gmul(a0,0x0e) ^ gmul(a1,0x0b) ^ gmul(a2,0x0d) ^ gmul(a3,0x09));
        s[c+1] = (uint8_t)(gmul(a0,0x09) ^ gmul(a1,0x0e) ^ gmul(a2,0x0b) ^ gmul(a3,0x0d));
        s[c+2] = (uint8_t)(gmul(a0,0x0d) ^ gmul(a1,0x09) ^ gmul(a2,0x0e) ^ gmul(a3,0x0b));
        s[c+3] = (uint8_t)(gmul(a0,0x0b) ^ gmul(a1,0x0d) ^ gmul(a2,0x09) ^ gmul(a3,0x0e));
    }
}

static void encrypt_block(const aes256_ctx *ctx, uint8_t *block) {
    uint8_t s[16];
    for (int i = 0; i < 16; i++) s[i] = block[i];
    add_round_key(s, ctx->round_key);
    for (int r = 1; r < 14; r++) {
        sub_bytes(s);
        shift_rows(s);
        mix_columns(s);
        add_round_key(s, ctx->round_key + r*16);
    }
    sub_bytes(s);
    shift_rows(s);
    add_round_key(s, ctx->round_key + 14*16);
    for (int i = 0; i < 16; i++) block[i] = s[i];
}

static void decrypt_block(const aes256_ctx *ctx, uint8_t *block) {
    uint8_t s[16];
    for (int i = 0; i < 16; i++) s[i] = block[i];
    add_round_key(s, ctx->round_key + 14*16);
    for (int r = 13; r >= 1; r--) {
        inv_shift_rows(s);
        inv_sub_bytes(s);
        add_round_key(s, ctx->round_key + r*16);
        inv_mix_columns(s);
    }
    inv_shift_rows(s);
    inv_sub_bytes(s);
    add_round_key(s, ctx->round_key);
    for (int i = 0; i < 16; i++) block[i] = s[i];
}

void aes256_cbc_encrypt(uint8_t *data, size_t len, const uint8_t key[32], const uint8_t iv[16]) {
    aes256_ctx ctx;
    key_expansion(&ctx, key);
    uint8_t prev[16];
    for (int i = 0; i < 16; i++) prev[i] = iv[i];
    for (size_t off = 0; off < len; off += 16) {
        for (int i = 0; i < 16; i++) data[off+i] ^= prev[i];
        encrypt_block(&ctx, data + off);
        for (int i = 0; i < 16; i++) prev[i] = data[off+i];
    }
}

void aes256_cbc_decrypt(uint8_t *data, size_t len, const uint8_t key[32], const uint8_t iv[16]) {
    aes256_ctx ctx;
    key_expansion(&ctx, key);
    uint8_t prev[16], cur[16];
    for (int i = 0; i < 16; i++) prev[i] = iv[i];
    for (size_t off = 0; off < len; off += 16) {
        for (int i = 0; i < 16; i++) cur[i] = data[off+i];
        decrypt_block(&ctx, data + off);
        for (int i = 0; i < 16; i++) data[off+i] ^= prev[i];
        for (int i = 0; i < 16; i++) prev[i] = cur[i];
    }
}

void pkcs7_pad(const uint8_t *src, size_t srclen, uint8_t *dst, size_t *dstlen) {
    size_t pad = 16 - (srclen % 16);
    for (size_t i = 0; i < srclen; i++) dst[i] = src[i];
    for (size_t i = 0; i < pad; i++) dst[srclen + i] = (uint8_t)pad;
    *dstlen = srclen + pad;
}

int pkcs7_unpad(uint8_t *buf, size_t *len) {
    if (*len == 0 || *len % 16 != 0) return -1;
    uint8_t pad = buf[*len - 1];
    if (pad == 0 || pad > 16 || pad > *len) return -1;
    for (size_t i = *len - pad; i < *len; i++)
        if (buf[i] != pad) return -1;
    *len -= pad;
    return 0;
}
